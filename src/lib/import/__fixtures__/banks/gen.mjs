async function xlsx(name, sheets) {
  const wb = new ExcelJS.Workbook();
  for (const { title, rows, merges = [] } of sheets) {
    const ws = wb.addWorksheet(title, { views: [{ rightToLeft: true }] });
    rows.forEach((r) => ws.addRow(r));
    merges.forEach((m) => ws.mergeCells(m));
  }
  await wb.xlsx.writeFile(out(name));
}
